def eval_poly(x, coeffs):
    """Evaluate y = a5*x^5 + a4*x^4 + a3*x^3 + a2*x^2 + a1*x + a0"""
    a5, a4, a3, a2, a1, a0 = coeffs
    return a5*x**5 + a4*x**4 + a3*x**3 + a2*x**2 + a1*x + a0

def plot_group(ax, coeffs_list, title, x_range=(0, 420)):
    """Plot one group of lane lines on the given axes."""
    x = np.linspace(x_range[0], x_range[1], 1000)
    for i, coeffs in enumerate(coeffs_list):
        y = eval_poly(x, coeffs)
        ax.plot(x, y)
    ax.set_xlabel('x (longitudinal distance)')
    ax.set_ylabel('y (lateral offset)')
    ax.set_title(title)
    ax.grid(True, alpha=0.3)

